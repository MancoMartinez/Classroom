-- Q3. Alcance. Cobertura tender/header por dia y tipo de transaccion, tienda CHA266.
SELECT h.TRADINGDAY, h.TRANSACTIONTYPE, COUNT(*) headers, COUNT(t.TRANSACTIONID) con_tender
FROM ARDMPROD.ARDM_356.ARDM_HEADER h
LEFT JOIN (SELECT DISTINCT TRANSACTIONID, TRADINGDAY FROM ARDMPROD.ARDM_356.ARDM_TENDER WHERE TRADINGDAY >= '2026-08-01') t
  ON t.TRANSACTIONID = h.TRANSACTIONID AND t.TRADINGDAY = h.TRADINGDAY
WHERE h.TRADINGDAY >= '2026-08-01' AND h.STORENO = 'CHA266'
GROUP BY 1, 2 ORDER BY 1, 2;

-- Q4. Mismo corte en toda la cadena, solo ratio diario. Si cae en una fecha, es carga. Si es estable y bajo en devoluciones, es mapeo.
SELECT h.TRADINGDAY, h.TRANSACTIONTYPE, COUNT(*) headers, COUNT(t.TRANSACTIONID) con_tender, ROUND(COUNT(t.TRANSACTIONID) / COUNT(*), 3) ratio
FROM ARDMPROD.ARDM_356.ARDM_HEADER h
LEFT JOIN (SELECT DISTINCT TRANSACTIONID, TRADINGDAY FROM ARDMPROD.ARDM_356.ARDM_TENDER WHERE TRADINGDAY >= '2026-08-01') t
  ON t.TRANSACTIONID = h.TRANSACTIONID AND t.TRADINGDAY = h.TRADINGDAY
WHERE h.TRADINGDAY >= '2026-08-01'
GROUP BY 1, 2 ORDER BY 1, 2;
