-- RCS-28992, segunda verificacion, solo SELECT, Snowflake Prod, schema ARDM_PRODUCTION.C163_ICA
-- Resultado de la primera: HEADER 1, TENDER 4, TRANSACTIONDISCOUNT 32, ITEM 38.
-- Compara filas contra contenidos distintos. Si filas es mayor que distintos, hay filas repetidas.
-- Si otra columna cambia solo por inserccion, agregala al EXCLUDE.
SELECT 'TENDER' AS tabla, COUNT(*) AS filas, COUNT(DISTINCT h) AS contenidos_distintos
FROM (SELECT HASH(*) AS h FROM (SELECT * EXCLUDE (RECORDSEQNO, INSERTEDDATETIME, UPDATEDDATETIME) FROM ARDM_PRODUCTION.C163_ICA.ARDM_TENDER WHERE TRANSACTIONID = 2609179959263358647))
UNION ALL
SELECT 'TRANSACTIONDISCOUNT', COUNT(*), COUNT(DISTINCT h)
FROM (SELECT HASH(*) AS h FROM (SELECT * EXCLUDE (RECORDSEQNO, INSERTEDDATETIME, UPDATEDDATETIME) FROM ARDM_PRODUCTION.C163_ICA.ARDM_TRANSACTIONDISCOUNT WHERE TRANSACTIONID = 2609179959263358647))
UNION ALL
SELECT 'ITEM', COUNT(*), COUNT(DISTINCT h)
FROM (SELECT HASH(*) AS h FROM (SELECT * EXCLUDE (RECORDSEQNO, INSERTEDDATETIME, UPDATEDDATETIME) FROM ARDM_PRODUCTION.C163_ICA.ARDM_ITEM WHERE TRANSACTIONID = 2609179959263358647));
